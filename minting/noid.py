"""
Port of the noid identifier algorithms used by the legacy ARK service.

Only the *pure* parts of Noid4Php are reproduced here: template parsing, the
character repertoires, base conversion (``n2xdig``) and the check character.
The stateful legacy machinery — Perl's ``rand()`` emulation, the queue/hold
lists and the ``:/…`` counter rows — is deliberately absent; ordering and
uniqueness are handled by the database instead (see ``minting.minter``).

Every function here is pinned to the legacy implementation by the conformance
vectors in ``tests/fixtures/noid_vectors.json``, which are generated by running
the original PHP (``tests/fixtures/generate_vectors.php``).

Original algorithms: John A. Kunze (UC Regents, 2002-2006), PHP port by
Daniel Berthereau. See legacy/library/Noid4Php.
"""

from __future__ import annotations

import re
from dataclasses import dataclass

#: Returned as ``total`` by templates that can mint without an upper bound.
NOLIMIT = -1

#: Character repertoires. All have a prime cardinality except "d" (digits).
ALPHABETS: dict[str, str] = {
    # Standard.
    "d": "0123456789",
    "e": "0123456789bcdfghjkmnpqrstvwxz",
    # Proposed.
    "i": "0123456789x",
    "x": "0123456789abcdef_",
    "v": "0123456789abcdefghijklmnopqrstuvwxyz_",
    "E": "123456789bcdfghjkmnpqrstvwxzBCDFGHJKMNPQRSTVWXZ",
    "w": "0123456789abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ#*+@_",
    # Proposed for the "c" mask, but not accepted for ARK.
    "c": "!\"#$&'()*+,0123456789:;<=>?@ABCDEFGHIJKLMNOPQRSTUVWXYZ[]^_`"
    "abcdefghijklmnopqrstuvwxyz{|}~",
    # Not in the Perl script, but ARK-compatible and the longest alphanumeric one.
    "l": "0123456789abcdefghijkmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ",
}

#: Maps a mask character to the repertoire its check character is drawn from.
#: Insertion order matters: :func:`check_repertoire` returns the first (shortest)
#: repertoire that covers every character, exactly as the legacy code did.
ALPHABET_CHECKS: dict[str, str] = {
    # For compatibility with the Perl script the check character is "e" for masks
    # made of "d" or "e", whatever the prefix.
    "d": "e",
    "i": "e",
    "x": "x",
    "e": "e",
    "v": "v",
    "E": "E",
    "l": "l",
    "w": "w",
    "c": "c",
}

#: Mask characters that select a repertoire.
REPERTOIRES = "dixevElwc"

_MASK_RE = re.compile(rf"^[rsz][{REPERTOIRES}]+k?$")
_TEMPLATE_RE = re.compile(rf"^([^.]*)\.([rsz][{REPERTOIRES}]+k?)$")
_DE_MASK_RE = re.compile(r"^.[de]+k$")

#: The templates the admin UI offers, in the order the legacy UI listed them.
#: Descriptions paraphrase the noid manual; capacity is computed, not stated,
#: so it can never disagree with the minter (see :func:`template_choices`).
TEMPLATE_CATALOGUE: tuple[tuple[str, str], ...] = (
    (".rddd", "Random 3-digit numbers."),
    (".sdddddd", "Sequential 6-digit numbers."),
    (".zd", "Sequential numbers without limit; new digits are added as needed."),
    (".rdddd", "Random 4-digit numbers."),
    (".sdd", "Sequential 2-digit numbers."),
    (".se", "Sequential single extended digits (0-9 and bcdfghjkmnpqrstvwxz)."),
    (".reee", "Random 3-extended-digit numbers."),
    (".zeee", "Sequential numbers without limit, at least 3 extended digits."),
    (".rdedeedd", "Random 7-character numbers, extended digits at positions 2, 4 and 5."),
    (".zededede", "Mixed digits without limit; new extended digits are added as needed."),
    (".sdede", "Sequential 4-mixed-digit numbers."),
    (
        ".rdedk",
        "Random 3 mixed digits plus a final computed check character. Prefix limited to 0-9 and bcdfghjkmnpqrstvwxz.",
    ),
    (
        ".sdeeedk",
        "5 sequential mixed digits plus a final extended-digit check character. Prefix limited to 0-9 and bcdfghjkmnpqrstvwxz.",
    ),
    (
        ".zdeek",
        "Sequential digits plus a check character, without limit. Prefix limited to 0-9 and bcdfghjkmnpqrstvwxz.",
    ),
    (
        ".redek",
        "Random 4 mixed digits, the last one a check character. Prefix limited to 0-9 and bcdfghjkmnpqrstvwxz.",
    ),
    (
        ".reedeedk",
        "Random 7 mixed digits plus a check character. Prefix limited to 0-9 and bcdfghjkmnpqrstvwxz.",
    ),
)


class TemplateError(ValueError):
    """Raised when a template cannot mint identifiers."""

    def __init__(self, message: str, code: str = "invalid"):
        super().__init__(message)
        self.code = code


@dataclass(frozen=True)
class TemplateSpec:
    """The result of parsing a noid template such as ``utsc.zd``."""

    template: str
    prefix: str
    mask: str
    gen_type: str
    total: int
    synonym: str

    @property
    def unlimited(self) -> bool:
        """True when the template can mint without an upper bound (``z`` masks)."""
        return self.total == NOLIMIT

    @property
    def has_check_char(self) -> bool:
        """True when identifiers end in a computed check character."""
        return self.mask.endswith("k")

    @property
    def is_random(self) -> bool:
        return self.gen_type == "random"


def n2xdig(num: int, mask: str) -> str:
    """
    Render ``num`` in the mixed radix described by ``mask`` (without any prefix).

    A ``k`` in the mask becomes a literal ``+`` placeholder, which
    :func:`check_char` later replaces with the real check character. Returns an
    empty string when the mask is malformed.
    """
    if not mask or not _MASK_RE.match(mask):
        return ""

    out = ""
    var_width = False
    rmask = list(reversed(mask))
    alphabet = ""
    div = 0

    while num != 0 or not var_width:
        if not var_width:
            if not rmask:
                break
            char = rmask.pop(0)
            # Terminate on "r" or "s" even if num is not all used up yet.
            if char in ("r", "s"):
                break
            if char in ALPHABETS:
                alphabet = ALPHABETS[char]
                div = len(alphabet)
            elif char == "z":
                var_width = True  # re-uses the last div value
                continue
            elif char == "k":
                continue
        num, remainder = divmod(num, div)
        out = alphabet[remainder] + out

    if mask.endswith("k"):
        out += "+"
    return out


def check_char(identifier: str, alphabet: str = "e") -> str | None:
    """
    Compute or verify the trailing check character of ``identifier``.

    ``identifier`` is the *whole* ARK including NAAN and prefix (e.g.
    ``61220/utsc1+``), matching how the legacy minter calls this. A trailing
    ``+`` means "compute it"; any other trailing character is verified.

    Returns the identifier with a correct check character, or ``None`` when the
    alphabet is unusable or verification fails. Characters outside the alphabet
    contribute zero, as in the original.
    """
    if not identifier or not alphabet:
        return None

    if len(alphabet) == 1:
        if alphabet not in ALPHABETS:
            return None
        chars = ALPHABETS[alphabet]
    else:
        if alphabet not in ALPHABETS.values():
            return None
        chars = alphabet

    last_char = identifier[-1]
    body = identifier[:-1]

    total = 0
    for position, char in enumerate(body, start=1):
        index = chars.find(char)
        total += position * (index if index >= 0 else 0)

    computed = chars[total % len(chars)]
    if last_char in ("+", computed):
        return body + computed
    return None


def check_repertoire(template: str) -> str | None:
    """
    Return the repertoire the check character of ``template`` is drawn from.

    ``""`` means the template has no check character; ``None`` means the
    template is malformed or the repertoire cannot be determined. (The legacy
    function returned TRUE and FALSE respectively.)
    """
    match = _TEMPLATE_RE.match(template or "")
    if not match:
        return None
    prefix, mask = match.group(1), match.group(2)
    if not mask.endswith("k"):
        return ""

    # For compatibility with the Perl script, only "e" is allowed for masks made
    # exclusively of "d" and "e". The prefix is not checked here.
    if _DE_MASK_RE.match(mask):
        return "e"

    # Otherwise take the shortest repertoire containing every character that can
    # appear. There are subtleties ("x" has no "x", "E" has no "0"…), so build
    # the full set and test it.
    all_chars = set(prefix)
    for char in mask[1:-1]:
        all_chars.update(ALPHABETS[ALPHABET_CHECKS[char]])

    for repertoire in dict.fromkeys(ALPHABET_CHECKS.values()):
        if all_chars.issubset(set(ALPHABETS[repertoire])):
            return repertoire
    return None


def parse_template(template: str) -> TemplateSpec:
    """
    Parse a noid template such as ``utsc.zd`` into its prefix, mask and capacity.

    Raises :class:`TemplateError` if the template cannot mint identifiers. Note
    this rejects ``""`` and ``"-"``, which the legacy code accepted as "no
    minting possible" — a collection here must always be able to mint.
    """
    template = re.sub(r"[/\s]+$", "", template or "")
    match = re.match(r"^(.*/)?([^/]+)$", template)
    template = match.group(2) if match else ""

    if not template or template == "-":
        raise TemplateError("A template is required to mint identifiers.", code="empty")

    if "." not in template:
        raise TemplateError(
            'A template requires a "." to separate the prefix and the mask.', code="no_dot"
        )

    match = re.match(r"^([^.]*)\.(\w+)", template)
    if not match:
        raise TemplateError("No template mask - cannot generate identifiers.", code="no_mask")

    prefix, mask = match.group(1), match.group(2)

    if not re.match(r"^[rsz]", mask):
        raise TemplateError(
            'A mask must begin with "r" (random), "s" (sequential) or "z" (sequential unlimited).',
            code="bad_generator",
        )

    if not re.match(r"^.[^k]+k?$", mask):
        raise TemplateError(
            "Exactly one check character (k) is allowed, at the end of the mask.",
            code="bad_check_char",
        )

    if not re.match(rf"^.[{REPERTOIRES}]+k?$", mask):
        raise TemplateError(
            f'A mask may contain only the letters "{", ".join(ALPHABETS)}".',
            code="bad_repertoire",
        )

    if mask.endswith("k"):
        repertoire = check_repertoire(template)
        if repertoire is None:
            raise TemplateError(
                "The check character repertoire cannot be determined.", code="no_repertoire"
            )
        if repertoire:
            alphabet = ALPHABETS[repertoire]
            for char in prefix:
                if char != "/" and char not in alphabet:
                    # By construction only "[de]+" masks can reach this.
                    raise TemplateError(
                        'With a check character, a mask of type "[de]+" may contain only '
                        f'characters from "{ALPHABETS["e"]}".',
                        code="prefix_not_in_alphabet",
                    )

    # Short synonym for the template: prefix plus the number of variable
    # characters, with "+" when the length can grow. "ft.rddeek" -> "ft5".
    synonym = f"{prefix}{len(mask) - 1}"
    if mask.startswith("z"):
        synonym += "+"

    total = 1
    for char in mask:
        if char in ALPHABETS:
            total *= len(ALPHABETS[char])

    gen_type = "random" if mask.startswith("r") else "sequential"
    return TemplateSpec(
        template=template,
        prefix=prefix,
        mask=mask,
        gen_type=gen_type,
        total=NOLIMIT if mask.startswith("z") else total,
        synonym=synonym,
    )


def make_id(firstpart: str, mask: str, num: int, repertoire: str = "e") -> str | None:
    """
    Build the complete ARK for counter value ``num``.

    ``firstpart`` is the NAAN and prefix already joined (e.g. ``61220/utsc``),
    mirroring how the legacy minter assembled an identifier: render the number,
    prepend the firstpart, then resolve any check character.
    """
    identifier = firstpart + n2xdig(num, mask)
    if mask.endswith("k"):
        return check_char(identifier, repertoire)
    return identifier


def xdig2n(variable_part: str, mask: str) -> int:
    """
    Recover the counter value that :func:`n2xdig` turned into ``variable_part``.

    ``variable_part`` is the identifier with the firstpart (NAAN and prefix)
    already stripped; a trailing check character, if the mask has one, is
    ignored. Raises :class:`ValueError` for a malformed mask or a character
    outside the mask's alphabet.

    Only meaningful below the mask's capacity: fixed-width ``r``/``s`` masks
    silently truncate once their space is exhausted, so the mapping stops being
    injective there.
    """
    if not mask or not _MASK_RE.match(mask):
        raise ValueError(f"Malformed mask: {mask!r}")

    body = variable_part[:-1] if mask.endswith("k") else variable_part

    # Line the mask's repertoires up against the digits, right to left, in the
    # same order n2xdig consumed them.
    mask_chars = [c for c in mask if c in ALPHABETS]
    if mask.startswith("z") and mask_chars:
        # A "z" mask repeats its most significant repertoire as it grows.
        mask_chars = [mask_chars[0]] * (len(body) - len(mask_chars)) + mask_chars

    if len(body) != len(mask_chars):
        raise ValueError(f"{variable_part!r} does not fit mask {mask!r}")

    number = 0
    for char, repertoire in zip(body, mask_chars, strict=True):
        alphabet = ALPHABETS[repertoire]
        index = alphabet.find(char)
        if index < 0:
            raise ValueError(f"{char!r} is not in repertoire {repertoire!r}")
        number = number * len(alphabet) + index
    return number


def template_choices() -> list[dict]:
    """
    :data:`TEMPLATE_CATALOGUE` with each template's capacity worked out.

    The capacity is formatted for display: ``"unlimited"`` for the ``z``
    masks, otherwise the number with thousands separators.
    """
    choices = []
    for value, description in TEMPLATE_CATALOGUE:
        # The prefix does not affect capacity; any non-empty one parses.
        spec = parse_template("x" + value)
        capacity = "unlimited" if spec.unlimited else f"{spec.total:,}"
        choices.append(
            {
                "value": value,
                "description": description,
                "capacity": capacity,
                "gen_type": spec.gen_type,
                "unlimited": spec.unlimited,
            }
        )
    return choices


def template_groups() -> list[tuple[str, list[dict]]]:
    """
    :func:`template_choices` split by how they mint, for ``<optgroup>`` headings.

    Sequential without limit first (the ``z`` masks; production uses ``.zd``),
    then sequential with a fixed size, then random (always a fixed size).
    Catalogue order is kept within each group.
    """
    groups: dict[str, list[dict]] = {
        "Sequential, no limit": [],
        "Sequential, fixed size": [],
        "Random": [],
    }
    for choice in template_choices():
        if choice["gen_type"] == "random":
            label = "Random"
        elif choice["unlimited"]:
            label = "Sequential, no limit"
        else:
            label = "Sequential, fixed size"
        groups[label].append(choice)
    return list(groups.items())
